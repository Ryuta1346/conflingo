const $ = s => document.querySelector(s);
let mode = new URLSearchParams(location.search).get('mode') === 'conference' ? 'conference' : 'meeting';
let permitted = false, overlay = null, fontSize = 18;
$('#mode').value = mode;
function render() {
  const conference = mode === 'conference', paused = $('#state').value === 'paused';
  const supportVisible = overlay ?? innerWidth >= 1346;
  $('#main').className = mode + (conference && !supportVisible ? ' support-hidden' : '');
  $('#mode-name').textContent = conference ? 'Conference' : 'Meeting';
  $('#eyebrow').textContent = conference ? 'Conference / 字幕' : 'Meeting / ライブ';
  $('#title').textContent = conference ? 'プロダクト発表セッション' : 'プロダクト定例';
  $('#subtitle').textContent = conference ? 'English → 日本語 · 辞書：プロダクト開発' : '自動保存オフ · 終了後に保存またはMarkdown書き出し';
  $('#utility').textContent = conference ? '字幕の設定' : '小さく表示';
  $('#transcript-title').textContent = conference ? '原文 · English' : '会話の流れ';
  $('.translated').hidden = !conference;
  $('#support-heading').textContent = conference ? 'AI支援' : 'いま、役立つ提案';
  $('#support-toggle').hidden = !conference;
  $('#support-toggle').textContent = supportVisible ? 'AI支援を閉じる' : 'AI支援を開く';
  $('#support-close').hidden = !conference || !supportVisible;
  $('#support').classList.toggle('overlay', conference && supportVisible && innerWidth < 1346);
  $('#save').hidden = $('#export').hidden = !conference;
  $('#save').disabled = !paused;
  $('#save').title = paused ? 'このMacに保存' : '停止後に保存できます';
  $('#save-status').textContent = conference ? paused ? '未保存' : '停止後に保存' : '';
  $('#end').hidden = conference;
  $('#pause').textContent = paused ? '再開' : conference ? '停止する' : '一時停止';
  $('#input-status').textContent = paused ? '○ 入力 停止中' : '● マイク・内部音声 取得中';
  $('.answer').hidden = $('#state').value === 'empty';
  $('.candidate').hidden = conference || $('#state').value === 'empty';
  $('#empty').hidden = $('#state').value !== 'empty';
  $('#sending').hidden = $('#state').value !== 'sending';
  document.querySelectorAll('[data-mode]').forEach(b => b.classList.toggle('active', b.dataset.mode === mode));
  permissions();
}
function permissions(){
  $('#ai-settings').textContent = permitted ? 'AI設定 · 許可済み' : 'AI設定 · オフ';
  $('#ai-status').textContent = permitted ? 'AI許可済み · 待機（モック）' : 'AI送信オフ · 許可はAI設定から';
  $('#ask').disabled = !permitted || !$('#question').value.trim();
  $('#stop-ai').hidden = !permitted;
  document.querySelectorAll('.child').forEach(c => { c.disabled = !permitted; });
  $('#automatic-docs').disabled = !permitted || !$('#automatic').checked;
}
function detail(title, html){$('#details-title').textContent=title;$('#details-content').innerHTML=html;$('#details').showModal();}
$('#mode').onchange = e => { mode=e.target.value; overlay=null; render(); };
document.querySelectorAll('[data-mode]').forEach(b => b.onclick = () => { mode=b.dataset.mode; $('#mode').value=mode; overlay=null; render(); });
$('#state').onchange=render;
$('#theme').onchange=e=>document.body.classList.toggle('dark',e.target.value==='dark');
$('#support-toggle').onclick=()=>{overlay=!(overlay ?? innerWidth >= 1346);render();};
$('#support-close').onclick=()=>{overlay=false;render();$('#support-toggle').focus();};
$('#ai-settings').onclick=()=>$('#settings').showModal();
$('#permission').onchange=e=>{permitted=e.target.checked;permissions();};
$('#automatic').onchange=permissions;
$('#stop-ai').onclick=()=>{permitted=false;$('#permission').checked=false;permissions();};
$('#question').oninput=permissions;
$('#ask').onclick=()=>{$('#state').value='sending';render();};
$('#documents').onclick=()=>detail('資料 · 2件','<p>資料操作は必要なときに開きます。Liveの結果欄には常設しません。</p><h3>pilot-plan.md</h3><h3>security-review.md</h3><p>追加・選択・検索・用語の操作は、実装では既存の資料パネルを再利用します。</p>');
$('#research').onclick=()=>detail('Webで調べる','<p>実装では既存のWeb調査画面を開き、検索語と送信許可を確認します。このモックは通信しません。</p>');
$('#llm').onclick=()=>detail('LLM設定','<p>実装では既存の接続設定を開きます。ここでは接続・APIキーの変更は行いません。</p>');
$('#reveal').onclick=()=>{overlay=false;render();$('#evidence').classList.add('highlight');$('#evidence').scrollIntoView({block:'center',behavior:'smooth'});};
$('#confirm').onclick=()=>{$('.candidate .badge').textContent='✓ 確認済み';};
$('#dismiss').onclick=()=>{$('.candidate .badge').textContent='× 却下';};
$('#pause').onclick=()=>{$('#state').value=$('#state').value==='paused'?'normal':'paused';render();};
$('#save').onclick=()=>{$('#save-status').textContent='保存済み（モック）';};
$('#export').onclick=()=>detail('Markdownを書き出す','<p>書き出しの位置を示すモックです。ファイルは作成しません。</p>');
$('#end').onclick=()=>detail('会議を終了しますか？','<p>DR1の終了確認を維持します。実装では、確定後に振り返りへ移ります。</p>');
$('#utility').onclick=()=>detail($('#utility').textContent,'<p>既存の画面・操作を維持します。このモックでは領域配分を確認します。</p>');
$('#pin').onclick=()=>$('#pin').setAttribute('aria-pressed',$('#pin').getAttribute('aria-pressed')!=='true');
$('#larger').onclick=()=>{fontSize=Math.min(48,fontSize+2);document.documentElement.style.setProperty('--read',fontSize+'px');};
$('#smaller').onclick=()=>{fontSize=Math.max(12,fontSize-2);document.documentElement.style.setProperty('--read',fontSize+'px');};
window.addEventListener('resize',render);
render();
